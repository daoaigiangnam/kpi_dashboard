    KEY idx_audit_actor_time (actor_user_id, occurred_at),
    KEY idx_audit_correlation (correlation_id),
    KEY idx_audit_result_time (result, occurred_at),
    CONSTRAINT fk_system_audit_business_entity FOREIGN KEY (business_entity_id) REFERENCES business_entities(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_system_audit_actor FOREIGN KEY (actor_user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_system_audit_result CHECK (result IN ('SUCCESS', 'FAILED', 'DENIED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

