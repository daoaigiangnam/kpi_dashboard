CREATE TABLE email_queue (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    event_key VARCHAR(190) NOT NULL,
    module_code VARCHAR(10) NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    business_entity_id BIGINT UNSIGNED NULL,
    recipient VARCHAR(500) NOT NULL,
    cc_json JSON NULL,
    bcc_json JSON NULL,
    subject VARCHAR(255) NOT NULL,
    html_body MEDIUMTEXT NULL,
    plain_body MEDIUMTEXT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    max_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 12,
    next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    locked_at DATETIME(3) NULL,
    locked_by VARCHAR(100) NULL,
    last_error TEXT NULL,
    message_id VARCHAR(255) NULL,
    sent_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uq_email_queue_event_key (event_key),
    KEY idx_email_queue_worker (status, next_attempt_at, id),
    KEY idx_email_queue_entity (business_entity_id, created_at),
    CONSTRAINT fk_email_queue_business_entity FOREIGN KEY (business_entity_id) REFERENCES business_entities(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_email_queue_module CHECK (module_code IN ('PL1', 'PL2', 'PL3', 'PL4', 'PL5', 'SYSTEM')),
    CONSTRAINT chk_email_queue_status CHECK (status IN ('PENDING', 'SENDING', 'RETRY', 'SENT', 'FAILED', 'CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE email_queue_attempts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    email_queue_id BIGINT UNSIGNED NOT NULL,
    attempt_no SMALLINT UNSIGNED NOT NULL,
    attempted_at DATETIME(3) NOT NULL,
    outcome VARCHAR(20) NOT NULL,
    error_code VARCHAR(100) NULL,
    sanitized_error TEXT NULL,
    smtp_message_id VARCHAR(255) NULL,
    duration_ms INT UNSIGNED NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_email_queue_attempt_no (email_queue_id, attempt_no),
    CONSTRAINT fk_email_queue_attempts_queue FOREIGN KEY (email_queue_id) REFERENCES email_queue(id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

