CREATE TABLE pl1_access_requests (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    business_entity_id BIGINT UNSIGNED NOT NULL,
    request_code VARCHAR(50) NOT NULL,
    request_type VARCHAR(20) NOT NULL,
    room_id BIGINT UNSIGNED NOT NULL,
    person_name VARCHAR(160) NOT NULL,
    person_email VARCHAR(190) NOT NULL,
    organization VARCHAR(160) NULL,
    role_reason VARCHAR(255) NOT NULL,
    access_level VARCHAR(30) NOT NULL,
    valid_from DATE NULL,
    valid_until DATE NULL,
    requester_name VARCHAR(160) NOT NULL,
    requester_email VARCHAR(190) NOT NULL,
    approver_name_snapshot VARCHAR(160) NOT NULL,
    approver_email_snapshot VARCHAR(190) NOT NULL,
    approval_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    submitted_at DATETIME(3) NOT NULL,
    decided_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uq_pl1_access_requests_entity (business_entity_id),
    UNIQUE KEY uq_pl1_access_requests_code (request_code),
    KEY idx_pl1_access_requests_room_person_status (room_id, person_email, approval_status),
    KEY idx_pl1_access_requests_status_submitted (approval_status, submitted_at),
    CONSTRAINT fk_pl1_access_requests_entity FOREIGN KEY (business_entity_id) REFERENCES business_entities(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_pl1_access_requests_room FOREIGN KEY (room_id) REFERENCES server_rooms(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_pl1_access_request_type CHECK (request_type IN ('NEW', 'CHANGE', 'REVOKE')),
    CONSTRAINT chk_pl1_access_request_status CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT chk_pl1_access_request_validity CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until >= valid_from)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE pl1_access_records (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    business_entity_id BIGINT UNSIGNED NOT NULL,
    room_id BIGINT UNSIGNED NOT NULL,
    person_name VARCHAR(160) NOT NULL,
    person_email VARCHAR(190) NOT NULL,
    organization VARCHAR(160) NULL,
    role_reason VARCHAR(255) NULL,
    access_level VARCHAR(30) NOT NULL,
    valid_from DATE NULL,
    valid_until DATE NULL,
    record_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_from_request_id BIGINT UNSIGNED NOT NULL,
    last_changed_by_request_id BIGINT UNSIGNED NULL,
    approved_by_name_snapshot VARCHAR(160) NULL,
    approved_at DATETIME(3) NULL,
    revoked_at DATETIME(3) NULL,
    expired_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uq_pl1_access_records_entity (business_entity_id),
    KEY idx_pl1_access_records_person_room_status (person_email, room_id, record_status),
    KEY idx_pl1_access_records_created_request (created_from_request_id),
    KEY idx_pl1_access_records_last_changed_request (last_changed_by_request_id),
    CONSTRAINT fk_pl1_access_records_entity FOREIGN KEY (business_entity_id) REFERENCES business_entities(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_pl1_access_records_room FOREIGN KEY (room_id) REFERENCES server_rooms(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_pl1_access_records_created_request FOREIGN KEY (created_from_request_id) REFERENCES pl1_access_requests(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_pl1_access_records_last_changed_request FOREIGN KEY (last_changed_by_request_id) REFERENCES pl1_access_requests(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_pl1_access_record_status CHECK (record_status IN ('ACTIVE', 'REVOKED', 'EXPIRED')),
    CONSTRAINT chk_pl1_access_record_validity CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until >= valid_from)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
